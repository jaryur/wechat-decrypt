def main():
    parser = argparse.ArgumentParser(description='导出微信朋友圈为 HTML')
    parser.add_argument('--user', help='只导出指定用户（wxid）')
    parser.add_argument('--merged', action='store_true', help='同时生成合并版 moments_full.html')
    args = parser.parse_args()

    print("读取朋友圈数据库...")
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    cur.execute('SELECT tid, user_name, content FROM SnsTimeLine ORDER BY tid ASC')
    rows = cur.fetchall()
    conn.close()
    print(f"  共 {len(rows)} 条记录，解析中...")

    moments = []
    for tid, user, content in rows:
        if not content:
            continue
        m = parse_moment(content)
        if m:
            moments.append(m)

    moments.sort(key=lambda x: x['time'] or datetime.datetime.min)
    print(f"  解析成功 {len(moments)} 条")

    # Build local image index
    print(f"扫描本地解密图片...")
    local_index = build_local_image_index()
    print(f"  找到 {len(local_index)} 张本地图片")

    # Group by user
    by_user = defaultdict(list)
    for m in moments:
        by_user[m['username']].append(m)

    # Filter if --user specified
    target_users = [args.user] if args.user else list(by_user.keys())
    if args.user and args.user not in by_user:
        print(f"[!] 未找到用户: {args.user}")
        sys.exit(1)

    os.makedirs(BY_USER_DIR, exist_ok=True)

    # Load month-grouped image index for gallery
    print("加载本地图片索引...")
    images_by_month = load_image_index_by_month()
    print(f"  共 {sum(len(v) for v in images_by_month.values())} 张图片，{len(images_by_month)} 个月份")

    # Stats for each user
    user_stats = {}
    total_local_hits = 0
    total_local_miss = 0

    for username in target_users:
        user_moments = by_user[username]
        nickname = user_moments[0]['nickname'] if user_moments else username

        # Prepare month-based fallback images for this user
        user_months = set()
        for m in user_moments:
            if m['time']:
                user_months.add(m['time'].strftime('%Y-%m'))
        
        # Build a deterministic fallback pool per month (sorted for consistency)
        month_images = {}
        for month in user_months:
            if month in images_by_month:
                month_images[month] = sorted(images_by_month[month])

        html_parts = []
        last_date = None
        local_hits = 0
        local_miss = 0
        fallback_hits = 0

        for idx, m in enumerate(user_moments):
            date_str = m['time'].strftime('%Y年%m月%d日') if m['time'] else '未知日期'
            if date_str != last_date:
                html_parts.append(f'<div class="date-divider"><span>{date_str}</span></div>')
                last_date = date_str
            html_parts.append(moment_html(m, idx, local_index, img_rel='../images', month_images=month_images))

            for mv in m['media']:
                if mv['type'] in ('2', '1'):
                    if mv['thumb_md5'] in local_index or mv['full_md5'] in local_index:
                        local_hits += 1
                    else:
                        local_miss += 1
                        # Check if fallback was used
                        month_key = m['time'].strftime('%Y-%m') if m['time'] else None
                        if month_key and month_key in month_images and len(month_images[month_key]) > 0:
                            fallback_hits += 1

        # Build month gallery HTML (appendix)
        gallery_html = ''
        matched_months = sorted(user_months & set(images_by_month.keys()), reverse=True)
        if matched_months:
            gallery_sections = []
            for month in matched_months:
                files = images_by_month[month]
                img_tags = ''
                for fname in files[:200]:
                    copied = copy_decoded_image_to_export(fname)
                    if copied:
                        img_tags += f'<a href="../images/{copied}" target="_blank"><img src="../images/{copied}" loading="lazy"></a>'
                if img_tags:
                    yr, mo = month.split('-')
                    title = f'📁 {yr}年{mo}月本地缓存 · {len(files)} 张（点击展开）'
                    gallery_sections.append(
                        f'<div class="month-gallery">'
                        f'<div class="gallery-title" onclick="toggleGallery(this)">{title}</div>'
                        f'<div class="gallery-grid">{img_tags}</div>'
                        f'</div>'
                    )
            if gallery_sections:
                gallery_html = (
                    '<div class="date-divider"><span>本地缓存图片</span></div>'
                    + '\n'.join(gallery_sections)
                )

        content_html = '\n'.join(html_parts)
        if gallery_html:
            content_html += '\n' + gallery_html

        valid_times = [m['time'] for m in user_moments if m['time']]
        if valid_times:
            oldest = min(valid_times).strftime('%Y.%m.%d')
            newest = max(valid_times).strftime('%Y.%m.%d')
            date_range = f'{oldest} – {newest}'
        else:
            date_range = ''

        user_path = os.path.join(BY_USER_DIR, f'{username}.html')
        html = build_html(
            content_html,
            f'{nickname} 的朋友圈',
            f'共 {len(user_moments)} 条 · {date_range}',
            img_rel='../images'
        )
        with open(user_path, 'w', encoding='utf-8') as f:
            f.write(html)

        user_stats[username] = {
            'nickname': nickname,
            'count': len(user_moments),
            'date_range': date_range,
        }
        total_local_hits += local_hits
        total_local_miss += local_miss
        print(f"  ✓ {esc(nickname)} ({username}): {len(user_moments)} 条 · md5命中:{local_hits} · 月份回退:{fallback_hits} · 缺失:{local_miss-fallback_hits} → {user_path}")

    # Generate overview index
    if not args.user:
        index_path = os.path.join(_export_base, 'index.html')
        html = user_list_html(user_stats)
        with open(index_path, 'w', encoding='utf-8') as f:
            f.write(html)
        print(f"\n📋 总览页: {index_path}")

    # Optionally generate merged version
    if args.merged and not args.user:
        print("\n生成合并版...")
        html_parts = []
        last_date = None
        for idx, m in enumerate(moments):
            date_str = m['time'].strftime('%Y年%m月%d日') if m['time'] else '未知日期'
            if date_str != last_date:
                html_parts.append(f'<div class="date-divider"><span>{date_str}</span></div>')
                last_date = date_str
            html_parts.append(moment_html(m, idx, local_index, img_rel='images'))

        content_html = '\n'.join(html_parts)
        valid_times = [m['time'] for m in moments if m['time']]
        date_range = ''
        if valid_times:
            date_range = f'{min(valid_times).strftime("%Y.%m.%d")} – {max(valid_times).strftime("%Y.%m.%d")}'

        html = build_html(content_html, '朋友圈归档', f'共 {len(moments)} 条 · {date_range}', img_rel='images')
        with open(OUT_PATH, 'w', encoding='utf-8') as f:
            f.write(html)
        print(f"  合并版: {OUT_PATH}")

    print(f"\n✅ 导出完成")
    print(f"   共 {len(user_stats)} 位用户")
    print(f"   本地图片命中：{total_local_hits}，缺失：{total_local_miss}")
    print(f"   输出目录：{_export_base}")


if __name__ == '__main__':
    main()
