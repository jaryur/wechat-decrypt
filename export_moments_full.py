def parse_moment(content):
    try:
        root = ET.fromstring(content)
    except ET.ParseError:
        return None

    obj = root.find('TimelineObject')
    extra = root.find('LocalExtraInfo')
    if obj is None:
        return None

    post_id = obj.findtext('id', '')
    username = obj.findtext('username', '')
    ts = obj.findtext('createTime', '0')
    dt = datetime.datetime.fromtimestamp(int(ts)) if ts and ts.isdigit() else None
    text = obj.findtext('contentDesc', '').strip()
    content_type = obj.findtext('.//ContentObject/type', '0')

    nickname = ''
    if extra is not None:
        nickname = extra.findtext('nickname', '')

    loc = obj.find('location')
    location = ''
    if loc is not None:
        location = loc.get('poiName', '') or ''

    media_items = []
    for media in obj.findall('.//mediaList/media'):
        mtype = media.findtext('type', '0')
        thumb_el = media.find('thumb')
        url_el = media.find('url')
        thumb_url = thumb_el.text if thumb_el is not None else ''
        full_url = url_el.text if url_el is not None else ''
        thumb_md5 = thumb_el.get('md5', '') if thumb_el is not None else ''
        full_md5 = url_el.get('md5', '') if url_el is not None else ''
        videomd5 = url_el.get('videomd5', '') if url_el is not None else ''
        size_el = media.find('size')
        w = size_el.get('width', '') if size_el is not None else ''
        h = size_el.get('height', '') if size_el is not None else ''
        media_items.append({
            'type': mtype,
            'thumb': thumb_url,
            'url': full_url,
            'thumb_md5': thumb_md5,
            'full_md5': full_md5,
            'videomd5': videomd5,
            'width': w,
            'height': h,
        })

    link_title = obj.findtext('.//appInfo/title', '') or obj.findtext('.//title', '')
    link_desc = obj.findtext('.//appInfo/desc', '') or obj.findtext('.//desc', '')
    link_url = obj.findtext('.//appInfo/url', '') or obj.findtext('.//url', '')

    likes = []
    for u in obj.findall('.//likeUserList/likeUser'):
        n = u.findtext('nickName', '')
        if n:
            likes.append(n)

    comments = []
    for c in obj.findall('.//commentList/comment'):
        cfrom = c.findtext('nickName', '') or c.findtext('username', '')
        ctxt = c.findtext('content', '')
        reply_to = c.findtext('replyCommentNickName', '')
        if ctxt:
            comments.append({'from': cfrom, 'text': ctxt, 'reply_to': reply_to})

    return {
        'id': post_id,
        'username': username,
        'nickname': nickname or username,
        'time': dt,
        'text': text,
        'type': content_type,
        'media': media_items,
        'location': location,
        'likes': likes,
        'comments': comments,
        'link_title': link_title,
        'link_desc': link_desc,
        'link_url': link_url,
    }


def build_local_image_index():
    """Build MD5 -> filename index from decoded_images/sns/ directory.
    
    First tries to load md5_index.json (content md5 -> filename),
    which is generated by computing md5 of decrypted image contents.
    Falls back to filename-based index if not available.
    """
    index = {}
    md5_index_path = os.path.join(os.path.dirname(SNS_DECODED_DIR), 'md5_index.json')
    if os.path.exists(md5_index_path):
        try:
            with open(md5_index_path, 'r') as f:
                index = json.load(f)
            return index
        except Exception:
            pass
    
    # Fallback: filename-based index (may not match XML md5s)
    if not os.path.exists(SNS_DECODED_DIR):
        return index
    for fname in os.listdir(SNS_DECODED_DIR):
        if '.' not in fname:
            continue
        base = fname.rsplit('.', 1)[0]
        ext = fname.rsplit('.', 1)[1].lower()
        if ext in ('jpg', 'jpeg', 'png', 'webp', 'gif', 'hevc'):
            index[base] = fname
    return index


def load_image_index_by_month():
    """Load image_index.jsonl and group by month.
    If the index file doesn't exist, auto-generate it by scanning cache dir.
    Returns: {month: [filename, ...]}
    """
    # Try script dir first (survives rm -rf of export dir)
    index_file = os.path.join(_script_dir, 'image_index.jsonl')
    if not os.path.exists(index_file):
        index_file = os.path.join(_export_base, 'image_index.jsonl')
    
    by_month = defaultdict(list)
    
    # Auto-generate if not exists
    if not os.path.exists(index_file):
        print("自动生成图片月份索引...")
        cache_base = _cfg.get('cache_dir', '')
        if cache_base and os.path.exists(cache_base):
            for root, dirs, files in os.walk(cache_base):
                if 'Sns/Img' not in root:
                    continue
                for fname in files:
                    if '.' in fname:
                        continue
                    for ext in ('jpg', 'jpeg', 'png', 'webp', 'gif', 'hevc'):
                        dec_path = os.path.join(SNS_DECODED_DIR, f'{fname}.{ext}')
                        if os.path.exists(dec_path):
                            month = 'unknown'
                            for p in root.split(os.sep):
                                if len(p) == 7 and p[4] == '-':
                                    month = p
                                    break
                            by_month[month].append(f'{fname}.{ext}')
                            break
            # Save for next time
            try:
                with open(index_file, 'w', encoding='utf-8') as f:
                    for month, files in by_month.items():
                        for fname in files:
                            f.write(json.dumps({'file': fname, 'month': month}, ensure_ascii=False) + '\n')
                print(f"  索引已保存: {index_file}")
            except Exception as e:
                print(f"  索引保存失败: {e}")
        return by_month
    
    # Load existing index
    with open(index_file, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
                month = entry.get('month', 'unknown')
                fname = entry.get('file', '')
                if fname:
                    by_month[month].append(fname)
            except Exception:
                pass
    return by_month


def copy_image_to_export(md5, local_index):
    """Copy a local decoded image to the export images dir, return relative filename."""
    if not md5 or md5 not in local_index:
        return None
    src = os.path.join(SNS_DECODED_DIR, local_index[md5])
    fname = local_index[md5]
    dst = os.path.join(IMAGES_DIR, fname)
    if not os.path.exists(dst):
        os.makedirs(IMAGES_DIR, exist_ok=True)
        shutil.copy2(src, dst)
    return fname


def copy_decoded_image_to_export(fname):
    """Copy a specific decoded image file to the export images dir."""
    src = os.path.join(SNS_DECODED_DIR, fname)
    if not os.path.exists(src):
        return None
    dst = os.path.join(IMAGES_DIR, fname)
    if not os.path.exists(dst):
        os.makedirs(IMAGES_DIR, exist_ok=True)
        shutil.copy2(src, dst)
    return fname


def esc(s):
    return (s or '').replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def moment_html(m, idx, local_index, img_rel='images', month_images=None):
    time_str = m['time'].strftime('%Y年%m月%d日 %H:%M') if m['time'] else '未知时间'
    date_str = m['time'].strftime('%Y-%m-%d') if m['time'] else ''

    avatar_char = (m['nickname'] or '?')[0]
    color_idx = sum(ord(c) for c in (m['username'] or '?')) % 8
    colors = ['#FF6B6B','#4ECDC4','#45B7D1','#96CEB4','#FFEAA7','#DDA0DD','#98D8C8','#F7DC6F']
    avatar_color = colors[color_idx]

    text_html = ''
    if m['text']:
        text_html = f'<div class="post-text">{esc(m["text"]).replace(chr(10), "<br>")}</div>'

    media_html = ''
    images = [mv for mv in m['media'] if mv['type'] in ('2', '1')]
    # 视频判断：media.type == '6' 且 ContentObject.type == '15'，或者 media type 为 '15'
    videos = [mv for mv in m['media'] if mv['type'] == '15' or (m['type'] == '15' and mv['type'] == '6')]

    # Get month key for fallback local images
    month_key = m['time'].strftime('%Y-%m') if m['time'] else None
    fallback_pool = month_images.get(month_key, []) if month_images else []
    fallback_idx = [0]  # use list for mutable closure

    def get_fallback_image():
        if fallback_idx[0] < len(fallback_pool):
            fname = fallback_pool[fallback_idx[0]]
            fallback_idx[0] += 1
            copied = copy_decoded_image_to_export(fname)
            if copied:
                return f'{img_rel}/{copied}'
        return None

    if images:
        n = len(images)
        grid_class = f'grid-{min(n, 3)}'
        img_tags = ''
        for mv in images:
            # Try local images first (md5 match)
            thumb_local = copy_image_to_export(mv['thumb_md5'], local_index)
            full_local = copy_image_to_export(mv['full_md5'], local_index)

            if thumb_local:
                src = f'{img_rel}/{thumb_local}'
                full = f'{img_rel}/{thumb_local}'
            elif full_local:
                src = f'{img_rel}/{full_local}'
                full = f'{img_rel}/{full_local}'
            else:
                # Fallback: use local month images instead of CDN
                local_src = get_fallback_image()
                if local_src:
                    src = local_src
                    full = local_src
                else:
                    src = mv['thumb'] or mv['url']
                    full = mv['url'] or mv['thumb']

            if src:
                is_local = thumb_local or full_local or local_src
                onerror = '' if is_local else 'onerror="this.style.display=\'none\';this.parentNode.classList.add(\'img-dead\')"'
                img_tags += (
                    f'<a href="{esc(full)}" target="_blank">'
                    f'<img src="{esc(src)}" loading="lazy" {onerror}>'
                    f'</a>'
                )
            else:
                img_tags += f'<div class="img-placeholder">🖼</div>'
        media_html = f'<div class="media-grid {grid_class}">{img_tags}</div>'

    if videos:
        for mv in videos:
            thumb_local = copy_image_to_export(mv['thumb_md5'], local_index)
            poster = f'{img_rel}/{thumb_local}' if thumb_local else (mv['thumb'] or '')
            video_src = mv['url'] or mv['thumb'] or ''
            if video_src:
                media_html += (
                    f'<div class="video-wrapper">'
                    f'<video controls preload="none" poster="{esc(poster)}" style="max-width:100%;border-radius:6px;">'
                    f'<source src="{esc(video_src)}" type="video/mp4">'
                    f'</video>'
                    f'</div>'
                )
            elif poster:
                media_html += (
                    f'<div class="video-placeholder">'
                    f'<img src="{esc(poster)}" loading="lazy" '
                    f'onerror="this.closest(\'.video-placeholder\').innerHTML=\'🎬 视频\'">'
                    f'<span class="play-icon">▶</span></div>'
                )

    link_html = ''
    if m['link_title']:
        href = esc(m['link_url'] or '#')
        link_html = f'''<a class="link-card" href="{href}" target="_blank">
            <div class="link-title">{esc(m["link_title"])}</div>
            <div class="link-desc">{esc(m["link_desc"] or "")}</div>
        </a>'''

    loc_html = f'<span class="location">📍 {esc(m["location"])}</span>' if m['location'] else ''

    likes_html = ''
    if m['likes']:
        likes_html = f'<div class="likes">❤ {esc("、".join(m["likes"]))}</div>'

    comments_html = ''
    if m['comments']:
        items = ''
        for c in m['comments']:
            fn = esc(c['from'])
            ct = esc(c['text']).replace('\n', '<br>')
            if c['reply_to']:
                rt = esc(c['reply_to'])
                items += f'<div class="comment"><span class="cfrom">{fn}</span> 回复 <span class="cfrom">{rt}</span>：{ct}</div>'
            else:
                items += f'<div class="comment"><span class="cfrom">{fn}</span>：{ct}</div>'
        comments_html = f'<div class="comments">{items}</div>'

    return f'''<article class="post" id="post-{idx}" data-date="{date_str}">
  <div class="post-header">
    <div class="avatar" style="background:{avatar_color}">{esc(avatar_char)}</div>
    <div class="post-meta">
      <span class="nickname">{esc(m["nickname"])}</span>
      <span class="post-time">{time_str}</span>
      {loc_html}
    </div>
  </div>
  <div class="post-body">
    {text_html}
    {media_html}
    {link_html}
  </div>
  {likes_html}
  {comments_html}
</article>'''


