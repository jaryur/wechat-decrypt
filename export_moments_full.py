def user_list_html(users):
    """Generate the overview index page listing all users."""
    items = ''
    for username, info in sorted(users.items(), key=lambda x: x[1]['count'], reverse=True):
        nickname = info['nickname'] or username
        count = info['count']
        date_range = info['date_range']
        avatar_char = (nickname or '?')[0]
        color_idx = sum(ord(c) for c in (username or '?')) % 8
        colors = ['#FF6B6B','#4ECDC4','#45B7D1','#96CEB4','#FFEAA7','#DDA0DD','#98D8C8','#F7DC6F']
        avatar_color = colors[color_idx]
        items += (
            f'<a class="user-card" href="by_user/{username}.html">'
            f'<div class="avatar" style="background:{avatar_color}">{esc(avatar_char)}</div>'
            f'<div class="user-info">'
            f'<div class="nickname">{esc(nickname)}</div>'
            f'<div class="stats">{count} 条朋友圈 · {date_range}</div>'
            f'</div></a>'
        )

    content = f'<div class="user-list">{items}</div>'
    return build_html(content, '朋友圈好友列表', f'共 {len(users)} 位好友')


